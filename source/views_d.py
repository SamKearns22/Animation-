def _hair(sp):
    """(top colour, clipped-side colour, kind, length below the ear), from the person's front design."""
    st = sp.get('hair')
    c, skin = sp.get('hair_c', (60, 44, 34)), sp['skin']
    side = blend(skin, c, 0.42) if st == 'fade' else c
    kind = 'bald' if st in BALD else ('long' if st in LONG_HAIR else 'short')
    return c, side, kind, LONG_HAIR.get(st, 0)


def _beard_col(sp):
    skin, c = sp['skin'], sp.get('beard_c', sp.get('hair_c', (90, 80, 74)))
    light = sp.get('beard') in ('short', 'stubble')   # a goatee as dark as the face-on one (Sam, 10 Nov)
    return blend(skin, c, 0.55 if light else 0.9), blend(skin, c, 0.85 if light else 1.0)


def _sits(j):
    """Seated, for rule 80's lap check: the pose says so, or the body is down a seat's drop with the feet out in front
    (a set that paints its own seat turns 'seated' off; a crouch or kneel has its feet under or behind the body)."""
    feet = [j.get('foot' + s) for s in 'LR']
    return bool(j.get('seated') or (j.get('bob', 0) >= 150 and all(f and len(f) > 2 and f[2] >= 0.5 * THIGH
                                                                       for f in feet)))


