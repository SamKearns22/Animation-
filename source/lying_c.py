def fall(sp, t, t0, x, z, facing, ground=0.0, pose='back', flip=1):
    """Falling backwards, in stages: moves.fall's knees buckling and drop onto the hips (the flat drawing, best
    side-on), then from the moment the hips land (t0 + 0.5) the 3D body takes over from that exact skeleton and
    settles back onto the shoulders into the lying pose over 0.45 s (eased: no pop). Returns ('views', j) or
    ('3d', Body, surfaces)."""
    if t < t0 + 0.5:
        return ('views', moves.fall(sp, t, t0)[0])
    j_sit = moves.fall(sp, t0 + 0.5, t0)[0]
    k0 = from_views(j_sit, sp, x, z, facing, ground)
    fx, fz = _unit(facing)
    yaw = math.degrees(math.atan2(fz, -fx))              # head towards the back of where they faced
    px, pz = k0['pelvis'][0], k0['pelvis'][2]
    k1, surf = lie(sp, pose, px, pz, yaw, ground, flip)
    k = blend(k0, k1, ease((t - t0 - 0.5) / 0.45))
    return ('3d', _brace(k, ground), surf)


def _brace(k, ground):
    """Going over backwards, the arms reach the floor before the back does (Open Wounds chat 16: the fallen worker's
    elbows hung 11-20 cm up in mid-settle, Elder Swindon 6): as the trunk tips past upright, each elbow is lowered
    onto the floor along its own side (the upper arm slopes down from the shoulder) and the forearm laid flat beyond
    it; eased in by the tilt, so no pop, and a pose already on the floor is left as it is."""
    up = _v(0, 1, 0)
    c = float(np.dot(_unit(k['neck'] - k['pelvis']), up))
    f = ease((0.9 - c) / 0.3)                        # 0 sitting up (cos 0.9), 1 by cos 0.6 (where the check starts)
    if f <= 0.0:
        return k
    k = k.copy()
    for side in 'LR':
        sh, el, wr = k['sh' + side], k['el' + side], k['wr' + side]
        hs = float(sh[1] - ground)
        low = ground + 0.05
        if el[1] <= low + 0.02:
            continue
        flat = _v(el[0] - sh[0], 0, el[2] - sh[2])
        if np.linalg.norm(flat) < 1e-4:
            flat = _v(wr[0] - sh[0], 0, wr[2] - sh[2])
        dy = min(UPPER * 0.999, max(0.0, hs - 0.05))
        e2 = sh + _unit(flat + 1e-9) * math.sqrt(UPPER ** 2 - dy ** 2) + _v(0, -dy, 0)
        e2[1] = max(e2[1], low)
        fl = _v(wr[0] - el[0], 0, wr[2] - el[2])
        if np.linalg.norm(fl) < 1e-4:
            fl = flat
        w2 = e2 + _unit(fl + 1e-9) * FORE
        w2[1] = ground + 0.044
        ne = el + (e2 - el) * f
        nw = wr + (w2 - wr) * f
        if ne[1] < el[1]:                            # only ever lowers an arm
            k['el' + side] = ne
            k['wr' + side] = nw
    return k


def place(cam, x, z, ground=0.0, height=1.75, arms=1.2):
    """Where a flat person standing at floor point (x, z) goes on screen through a 3D camera: (Xf, Yf) the floor point,
    s their drawing scale (height in metres: the skeleton is a 1.75 m person), and views.person's tilt (e, c): heights
    squash by c; a point one unit nearer the lens sits e units lower, measured at the arms' height (`arms` metres up,
    kit lesson, Patriots 3: measured at the floor, close up, a hand held out at chest height sank far too low, the
    salute to the chest)."""
    k = height / 1.75
    (Xf, Yf), _ = cam.project((x, ground, z))
    (_, _), km = cam.project((x, ground + 0.9, z))
    s = km * M * k
    (_, Yn), _ = cam.project((x, ground + 928 * M * k, z))
    c = max(0.15, min(1.0, (Yf - Yn) / (928 * s)))
    tc = _unit(_v(cam.pos[0] - x, 0, cam.pos[2] - z))   # how much lower a point 0.42 m nearer us sits (Prepper)
    (_, Ym), _ = cam.project((x, ground + arms, z))
    (_, Yq), _ = cam.project(tuple(_v(x, ground + arms, z) + tc * 0.42))
    e = max(V.ELEV, (Yq - Ym) / s / (0.42 / (M * k)))
    return Xf, Yf, s, e, c


def stand(img, cam, sp, x, z, facing, j, t, ground=0.0, head_facing=None, shadow_alpha=55, height=1.75):
    """Someone standing (or sitting: any views pose) at floor point (x, z), seen through a 3D camera at its real
    tilt. Up to views.HIGH degrees down: the flat drawing with the real tilt and a floor shadow; steeper: the 3D
    body of the same pose. Returns ('2d', views j2) or ('3d', joints on screen). (Placed by place().)"""
    mid = _v(x, ground + 0.9, z)
    d = mid - np.asarray(cam.pos, float)
    tilt = math.degrees(math.atan2(-d[1], math.hypot(d[0], d[2])))
    if tilt >= V.HIGH:
        k = from_views(j, sp, x, z, facing, ground, head_facing)
        return ('3d', draw_volumes(img, cam, k, sp, t, surfaces=[(_v(0, ground, 0), _v(0, 1, 0))]))
    ring = [(x + 0.3 * math.cos(u), ground + 0.004, z + 0.22 * math.sin(u)) for u in np.linspace(0, 2 * math.pi, 18)]
    if all(cam.depth(q) > 0.2 for q in ring):
        lay = Image.new('RGBA', img.size, (0, 0, 0, 0))
        B.Pen(lay, S.FLAT).poly([cam.project(q)[0] for q in ring], (0, 0, 0, shadow_alpha), None)
        img.alpha_composite(lay)
    Xf, Yf, s, e, c = place(cam, x, z, ground, height)
    yaw = cam.yaw_of((x, 0, z), facing)
    hy = cam.yaw_of((x, 0, z), head_facing) if head_facing is not None else None
    return ('2d', V.person(img, S.FLAT, Xf, Yf - 928 * s, s, sp, t, yaw, j, hy, tilt=(e, c)))


