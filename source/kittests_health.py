def _b_diff_colour(a, b):
    """The median colour, in picture a, of the pixels where pictures a and b differ (what one drawing adds)."""
    import numpy as np
    from PIL import Image
    A = np.asarray(Image.open(a).convert('RGB')).astype(int)
    B = np.asarray(Image.open(b).convert('RGB')).astype(int)
    m = np.abs(A - B).sum(2) > 30
    return tuple(int(v) for v in np.median(A[m], 0)) if m.sum() > 50 else None


def _b_beard_form(beard_png, none_png, colour):
    """How a drawn beard reads: the share of its pixels in one flat colour near the beard's own (a black patch), the
    spread of its brightness (10th to 90th in a hundred), and its median's distance from the beard's colour."""
    import numpy as np
    from PIL import Image
    A = np.asarray(Image.open(beard_png).convert('RGB')).astype(int)
    N = np.asarray(Image.open(none_png).convert('RGB')).astype(int)
    px = A[np.abs(A - N).sum(2) > 30]
    c = np.array(colour)
    lum = px.mean(1)
    return dict(flat=float((np.abs(px - c).sum(1) / 3 < 15).mean()),
                spread=float(np.percentile(lum, 90) - np.percentile(lum, 10)),
                far=float(np.abs(np.median(px, 0) - c).sum() / 3))


