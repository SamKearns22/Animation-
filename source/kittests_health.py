@test
def long_hair_one_piece():
    """B2, rule 89 hunt 1 critique (27 Nov): the long straight hair seen from behind read as a HOOD (an ink band across
    the back of the head where the crown's mass lay over the curtain, and a step in at the shoulders where the
    curtain's sides followed the jaw in), and at three-quarter white gaps showed between the neck and the hair. Drawn
    in a light test colour so ink shows against it: from behind no ink row runs across the hair's middle, the hair's
    outer edge never steps back in on the way down, and at three-quarter no background shows between hair and hair
    under the jaw. The old drawing fails all three (band, step and gaps measured on it, cost tests chat 4)."""
    import numpy as np
    import people
    import views as V
    import body as B
    from PIL import Image
    hc = np.array((176, 120, 70))
    sp = people.person(dict(who='badenoch', name='K', house=dict(name='badenoch', hair='long', look='detail')))
    sp['hair_c'] = tuple(int(v) for v in hc)                 # what the house head paints the hair with
    people.install({'badenoch': sp})

    def view(yaw):                                           # as facehouse.turns draws them (B.SS 1: one size)
        tile = Image.new('RGBA', (1080, 1920), (255, 255, 255, 255))
        ss, B.SS = B.SS, 1
        try:
            V.person(tile, B.Cam(1.0, 540, 960), 540, 900, 1.6, dict(sp), 0.0, yaw)
        finally:
            B.SS = ss
        return np.asarray(tile.convert('RGB')).astype(int)[230:1010, 150:930]
    a = view(180)
    hair = np.abs(a - hc).sum(2) < 60
    ink = a.sum(2) < 120
    rows = np.flatnonzero(hair.sum(1) > 20)
    top, low = rows[0], rows[0] + int((rows[-1] - rows[0]) * 0.8)
    band, step, keep = 0.0, 0, None
    for y in range(top, low):
        xs = np.flatnonzero(hair[y])
        if len(xs) < 20:
            continue
        x0, x1 = xs[0], xs[-1]
        mid = ink[y, x0 + (x1 - x0) // 4: x1 - (x1 - x0) // 4]
        band = max(band, mid.mean() if len(mid) else 0.0)
        if y > top + 30:
            keep = x0 if keep is None else min(keep, x0)
            step = max(step, int(x0 - keep))
    b = view(45)
    bh = np.abs(b - hc).sum(2) < 60
    bg = (b > 250).all(2)
    gaps = 0
    for y in range(int(780 * 0.55), int(780 * 0.95)):
        xs = np.flatnonzero(bh[y])
        if len(xs) > 10:
            gaps += int(bg[y, xs[0]:xs[-1]].sum())
    c = view(135)                                            # hunt 2: three-quarter behind must not read as straight
    skin = np.abs(c - np.array(sp['skin'])).sum(2) < 40      # behind: a slice of cheek and jaw down the face's side
    ch = np.flatnonzero((np.abs(c - hc).sum(2) < 60).sum(1) > 20)   # (the old one: a patch at the temple, a hole)
    cheek = (skin.sum(1) >= 3).sum() / max(1, ch[-1] - ch[0]) if len(ch) else 0.0
    ok = band < 0.4 and step <= 4 and gaps <= 20 and cheek >= 0.2
    return ok, (f"from behind: the most of a row across the hair's middle that is ink {band:.2f} (a band: over 0.4), the "
                f"outer edge stepping back in {step} px (over 4: a step); three-quarter: {gaps} background pixels "
                f"between hair and hair under the jaw (over 20: gaps); three-quarter behind: cheek shown down "
                f"{cheek:.2f} of the hair's height (under 0.2: it reads as straight behind)")

