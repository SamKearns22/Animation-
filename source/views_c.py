class Tilted:
    """A person's frame seen from a camera tilted down (Build list item 12, 25 Oct): heights squash by `c` towards
    `piv` (the soles), so a high camera sees shorter legs and body; `dy` instead only moves the drawing down by
    that much (the head: a ball looks round from any height, it only sits on the squashed neck)."""
    def __init__(self, L, c=1.0, piv=928.0, dy=None):
        self.L, self.cam, self.s, self.k, self.flip = L, L.cam, L.s, getattr(L, 'k', 1.0), getattr(L, 'flip', 1)
        self.c, self.piv, self.dy = c, piv, dy

    def P(self, x, y):
        if self.dy is not None:
            return self.L.P(x, y + self.dy)
        return self.L.P(x, self.piv + (y - self.piv) * self.c)

    def S(self, v):
        return self.L.S(v)


class Mirrored:
    """A head's frame flipped about its own centre line (x = cx): the head faces its own way, whichever way the body's
    drawing is mirrored (kit lesson, Patriots 3: a soldier facing us could not look to his other side)."""
    def __init__(self, L, cx):
        self.L, self.cx, self.cam, self.s, self.flip = L, cx, L.cam, L.s, -getattr(L, 'flip', 1)

    def P(self, x, y):
        return self.L.P(2 * self.cx - x, y)

    def S(self, v):
        return self.L.S(v)


class Rolled:
    """A head's frame tipped `deg` degrees about the top of the neck (pivot) and dropped `dy` units (a nod): the
    head acting of headlife.py (Job K, Sam: Y, 10 Nov), drawn inside the rig so every line stays sharp."""
    def __init__(self, L, deg, pivot, dy=0.0):
        self.L, self.cam, self.s, self.flip = L, L.cam, L.s, getattr(L, 'flip', 1)
        a = math.radians(deg)
        self.c, self.sn, (self.px, self.py), self.dy = math.cos(a), math.sin(a), pivot, dy

    def P(self, x, y):
        dx, dy = x - self.px, y - self.py
        return self.L.P(self.px + dx * self.c - dy * self.sn, self.py + dx * self.sn + dy * self.c + self.dy)

    def S(self, v):
        return self.L.S(v)


# A nod is a pitch, never a bob (Open Wounds chat 39, Sam's note 26, 26 Nov: "It's not a nod, it's a head-bob": the
# kit slid the whole head down and up). Learnt from a real nod side-on (notes/learn/nod: Wikimedia 'Nodding
# gesture', public domain): the head turns about a point just below and behind the ear (the top of the neck); the
# chin goes down and in toward the collar, the nose tips down, the ear and the back of the skull barely move, the neck
# and collar not at all. Drawn flat, each mark on the head is given a depth from a head-shaped ellipsoid (the face
# nearest us, the outline at the edge) and turned in 3D about that point, then seen straight on again: from the front
# the eyes, nose and mouth slide down inside the outline and the lower face shortens, the chin tucks over the
# collar, the crown moves about a third as far; side-on it is the reference's turn; three-quarter a mix.
NOD_DEG = 2.9          # degrees of pitch per nod unit: the face travels as far as the old bob's 5 units did, so the
#                        sizes Sam passed (chat 37: 12-16 px) stay; only the shape changed (chat 39: at 4.5 May's nod
#                        measured 25 px, comically large)
NOD_PIVOT = (0.35, 0.2)   # the pivot below the head's centre (of hh) and behind it (of the head's depth)
NOD_DEPTH = 1.15       # the head's depth front to back over its width (hw)
NOD_FACING = {'front': (0.0, 1.0), 'three': (0.70710678, 0.70710678), 'side': (1.0, 0.0),
              'three_back': (0.70710678, -0.70710678), 'back': (0.0, -1.0)}   # where the face points (x, toward us),
#                                                 in head units (turned heads face right: plain_head_view)


