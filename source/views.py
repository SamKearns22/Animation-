NOD_SOLID = [None]   # (centre x, brim y, half width, dome height) in head units while a solid hat is drawn


class Pitched:
    """A head's frame nodded `deg` degrees (chin down: +) about the top of the neck, in 3D (NOD_* above): a nod as
    the head turning, never sliding. `c` the head's centre (head units), hw/hh its half width and height, `view` the
    head's view."""
    def __init__(self, L, deg, c, hw, hh, view):
        self.L, self.cam, self.s, self.flip = L, L.cam, L.s, getattr(L, 'flip', 1)
        fx, fz = NOD_FACING.get(view, (0.0, 1.0))
        th = math.radians(deg)
        self.co, self.si = math.cos(th), math.sin(th)
        self.cx, self.cy, self.rx, self.ry, self.rz = c[0], c[1], hw, 1.1 * hh, NOD_DEPTH * hw
        self.f = np.array([fx, 0.0, fz])
        self.a = np.cross(self.f, [0.0, 1.0, 0.0])          # the axis: the forward line tips toward down (+y)
        self.pv = np.array([c[0], c[1] + NOD_PIVOT[0] * hh, 0.0]) - NOD_PIVOT[1] * self.rz * self.f

    def depth(self, x, y):
        """How far toward us the head's surface is at (x, y): an ellipsoid, the jaw fuller below the middle (the
        chin stands forward, so it tucks rather than staying on the outline). A solid worn on the head (NOD_SOLID:
        a hard hat) is its own dome on a flat brim, so it tips whole (chat 39: on the face's ellipsoid the brim,
        wider than the face, bent into a V)."""
        if NOD_SOLID[0] is not None:
            cx, yb, w, h = NOD_SOLID[0]
            a = (x - cx) / w
            b = min(0.0, y - yb) / h
            return self.rz * w / self.rx * math.sqrt(max(0.0, 1.0 - a * a - b * b))
        u, v = (x - self.cx) / self.rx, (y - self.cy) / self.ry
        q = u * u + (0.5 * v * v if v > 0 else v * v)
        return self.rz * math.sqrt(max(0.0, 1.0 - q))

    def P(self, x, y):
        v = np.array([x, y, self.depth(x, y)]) - self.pv
        a = self.a
        r = v * self.co + np.cross(a, v) * self.si + a * (a @ v) * (1 - self.co)
        return self.L.P(self.pv[0] + r[0], self.pv[1] + r[1])

    def S(self, v):
        return self.L.S(v)


WHITE = (250, 250, 248)                       # the whites of the eyes, in every head the kit draws


def _split_long(pts, most=10.0):
    """A closed outline with every edge longer than `most` head units cut into equal pieces (never shorter than
    most/2, so the line's joins stay as they were drawn)."""
    out = []
    for a, b in zip(pts, list(pts[1:]) + [pts[0]]):
        n = max(1, int(math.hypot(b[0] - a[0], b[1] - a[1]) // most))
        out += [(a[0] + (b[0] - a[0]) * k / n, a[1] + (b[1] - a[1]) * k / n) for k in range(n)]
    return out


class Eyes(B.Pen):
    """A head's pen that notes each eye as it is drawn (the white, then the pupil inside it), in screen pixels, so the
    look check measures where the pupils really point on screen (rule 43), never what the film meant them to. A real
    Pen (code that looks for one finds it); its drawing goes through the pen it wraps."""
    def __init__(self, pen):
        self.pen, self.found, self._white, self.marks = pen, [], None, []
        self.img, self.cam, self.d = pen.img, pen.cam, pen.d

    def __getattr__(self, k):
        return getattr(self.pen, k)

    def poly(self, pts, fill, line=INK, lw=4):
        self._note(fill, line, pts)
        if isinstance(self.pen.cam, Pitched):     # nodding: long straight edges cut short so they bend with the
            pts = _split_long(pts)                # turn (chat 39: a hard hat's brim of 7 points tipped into a V)
        return self.pen.poly(pts, fill, line, lw)

    def ell(self, cx, cy, rx, ry, fill, line=INK, lw=4, rot=0, n=40):
        self._note(fill, line, [(cx - rx, cy), (cx + rx, cy), (cx, cy - ry), (cx, cy + ry)])
        return self.pen.ell(cx, cy, rx, ry, fill, line, lw, rot, n)

    def line(self, pts, colr=INK, lw=4):
        self._mark(None, colr, pts)
        return B.Pen.line(self, pts, colr, lw)           # the same drawing path as before the mark was kept

    def _mark(self, fill, line, pts):
        """Every mark on the face, in the head's units (mouth_seen: does the face have a mouth, Sam's notes 5, 15, 45)."""
        try:
            q = np.array(pts, float)[:, :2]
            self.marks.append((q.min(0), q.max(0), None if fill is None else tuple(fill[:3]),
                               None if not line else tuple(line[:3])))
        except Exception:
            pass

    def _note(self, fill, line, pts):
        self._mark(fill, line, pts)
        if fill is None or len(fill) < 3:
            return
        q = np.array([self.pen.cam.P(*v) for v in pts], float)
        if tuple(fill[:3]) == WHITE:
            self._white = q
        elif self._white is not None and line is None and tuple(fill[:3]) == tuple(INK[:3]):
            w = self._white
            c = (w.max(0) + w.min(0)) / 2
            half = max(1.0, (w[:, 0].max() - w[:, 0].min()) / 2)
            self.found.append(dict(white=tuple(c), pupil=tuple(q.mean(0)), off=tuple((q.mean(0) - c) / half),
                                   half=half))
            self._white = None

    def mouth_seen(self, sp, view):
        """Rule 13 (Sam's notes 5, 15, 45: faces with no mouth): True when a mark is drawn where the mouth goes (a
        mouth, lips, or a moustache over them), measured from the eyes' whites (any face system draws them; sizes
        differ between systems, so the eye's width is the unit); False when the face is turned to us and nothing is
        there; None when it cannot tell (from behind, eyes shut or drawn without whites)."""
        if view not in ('front', 'three', 'side'):
            return None
        def pupil_in(lo, hi):                         # an eye's white has an iris or pupil inside it (teeth do not)
            return any(f is not None and min(f) < 232 and (l2 >= lo).all() and (h2 <= hi).all()
                       and (h2 - l2)[0] < (hi - lo)[0] for l2, h2, f, _ in self.marks)
        whites = [(lo, hi) for lo, hi, fill, _ in self.marks
                  if fill is not None and min(fill) >= 232 and hi[0] > lo[0] and pupil_in(lo, hi)]
        if not whites:
            return None
        u = max(hi[0] - lo[0] for lo, hi in whites)                  # an eye's width
        ex = np.mean([(lo[0] + hi[0]) / 2 for lo, hi in whites])
        ey = max((lo[1] + hi[1]) / 2 for lo, hi in whites)
        skin = tuple(sp.get('skin', ())[:3]) or None
        for lo, hi, fill, line in self.marks:
            cx, cy = (lo + hi) / 2
            if not (ey + 1.5 * u < cy < ey + 4.2 * u and abs(cx - ex) < 2.6 * u and hi[1] - lo[1] < 3 * u):
                continue
            if hi[0] - lo[0] < 0.3 * u:
                continue                              # a dot (stubble, a freckle) is not a mouth
            if line is None and (fill is None or fill == skin):
                continue                              # a skin-coloured shape (a cheek, a chin) is not a mouth
            return True
        return False


class Lean:
    """The drawing frame of the upper body, tipped by the pose's lean: a side view rotates about the hips; a front
    view foreshortens (the chest comes towards us and down)."""
    def __init__(self, L, lean, yaw, pivot=HIP_Y):
        self.L, self.cam, self.s, self.flip = L, L.cam, L.s, getattr(L, 'flip', 1)
        self.piv = pivot
        a = math.radians(lean)
        cy = abs(math.cos(math.radians(yaw)))
        self.k = (math.cos(a) - _E[0] * math.sin(a)) * cy + (1 - cy)
        self.r = a * math.sin(math.radians(yaw))
        self.c, self.s_ = math.cos(self.r), math.sin(self.r)

    def P(self, x, y):
        dy = (y - self.piv) * self.k
        return self.L.P(x * self.c - dy * self.s_, self.piv + x * self.s_ + dy * self.c)

    def S(self, v):
        return self.L.S(v)


