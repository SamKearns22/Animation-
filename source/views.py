def shoe_frame(j, side):
    """The shoe's own frame at the ankle: (dx across, dy down to the sole at 36, dz along to the toe at 92) to the body
    frame. `toe` lifts the toes (degrees; the heel-lift of a kick); `foot_yaw` turns the foot about the shin (a figure
    four's foot points across), `foot_roll` rolls it about its length (sitting.py)."""
    fx, fy, fz = j['foot' + side]
    a = math.radians(j.get('toe' + side, 0.0))
    yw, rl = j.get('foot_yaw' + side, 0.0), j.get('foot_roll' + side, 0.0)
    if not (yw or rl or j.get('sole' + side)):                        # every film before the sitting kit, unchanged
        return lambda dx, dy, dz: (fx + dx, fy + dy - dz * math.sin(a), fz + dz * math.cos(a))
    cy, sy = math.cos(math.radians(yw)), math.sin(math.radians(yw))
    cr, sr = math.cos(math.radians(rl)), math.sin(math.radians(rl))

    def pt(dx, dy, dz):
        x, y = dx * cr - dy * sr, dx * sr + dy * cr                   # roll about the foot's length
        y, z = y * math.cos(a) - dz * math.sin(a), y * math.sin(a) + dz * math.cos(a)   # toes up
        return (fx + x * cy + z * sy, fy + y, fz - x * sy + z * cy)  # turned about the vertical
    return pt


def check_arm3(j, side, where='an arm'):
    """The arm checker for skeleton arms, in 3D (on screen an arm pointing at the camera is rightly short): both bones
    at the rig's lengths, and the elbow never folded tighter than 25 degrees."""
    sh, el, wr = j['sh' + side], j['el' + side], j['wr' + side]
    u, f = _sub(el, sh), _sub(wr, el)
    lu, lf = math.sqrt(_dot(u, u)), math.sqrt(_dot(f, f))
    if lu > F.UPPER * 1.06 or lf > F.FORE * 1.06:
        F.fail(f'{where}: a bone is longer than the rig')
    cosang = _dot(_mul(u, -1), f) / ((lu * lf) or 1)
    if math.degrees(math.acos(max(-1.0, min(1.0, cosang)))) < 25:
        F.fail(f'{where}: elbow folded tighter than 25 degrees')
    # the elbow folded back across the body, in 3D (x is across the body, so no view or foreshortening can hide it):
    # the elbow well past the chest's centre line and the wrist back out beyond it (figure.audit_arm's test, on the bones)
    sgn = 1 if sh[0] >= 0 else -1
    if sgn * el[0] < sgn * sh[0] - 0.5 * F.UPPER and sgn * wr[0] > sgn * el[0] + 0.3 * F.FORE:
        if os.environ.get('ARM_FOLD_NAMED'):                 # Sam, 13 Nov: named on the animatic, not stopping it
            return F.named(f'{where}: elbow folded back across the body')
        raise F.FigureError(f'figure check: {where}: elbow folded back across the body (elbow on the chest, forearm '
                            f"pointing back out): bend the elbow 'out' or 'depth' (never excused by allow())")


