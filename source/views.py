def hands_onto(cam, x, y, s, sp, yaw, j, want, pole='down', shape='palm', rounds=6, size=(1080, 1920)):
    """Contact by screen (Patriots 5 chat 9, shot 6: from close behind Danny his palms 'on the sill' floated in the
    air as raised hands; the rig draws a body flat at one scale while the set is in true perspective, so a 3D target
    on the sill does not land on the drawn sill). want: {side: (world x, y)} where the set draws the thing the hand
    rests on (the hand's centre). Each hand's 3D target (torso frame) is moved, keeping its reach forward, until the
    drawn hand lands there (within a pixel); returns the pose and {side: miss in world px}. Kittest hands_onto_lands."""
    import body as B_
    seen = {}
    inner = B_.gesture_hand

    def spy(p, el, wr, shp, skin, *a, **k):
        d = (wr[0] - el[0], wr[1] - el[1])
        n = math.hypot(*d) or 1.0
        cx, cy = p.cam.P(wr[0] + d[0] / n * 12, wr[1] + d[1] / n * 12)
        seen[len(seen)] = (cx / B_.SS, cy / B_.SS)
        return inner(p, el, wr, shp, skin, *a, **k)
