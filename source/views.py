def _side_depths(sp, fig, bottom):
    """The side view's front and back depth at each height (the turned outline borrows them)."""
    poly = torso_outline(dict(sp, figure=fig), 'side', bottom)
    ys = np.arange(0.0, bottom + 1, 10.0)
