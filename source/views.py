def blend(a, b, k):
    return tuple(int(round(x + (y - x) * k)) for x, y in zip(a, b))


def snap(yaw):
    """Nearest drawn view (degrees 0-180) for an angle (0 = facing us, 90 = facing right, -90 = left, 180 = away),
    and whether it is mirrored (facing left)."""
    y = ((yaw + 180) % 360) - 180
    m = min(VIEWS, key=lambda v: abs(abs(y) - v))
    return m, y < 0


RAISED_OVER = True     # a hand raised in front of the face is drawn over the head (chat 8; kittests switch it off)


def project(p3, yaw):
    """A body point seen from the camera, the body facing `yaw` degrees: (screen x, y) and depth (+ = nearer)."""
    a = math.radians(yaw)
    x, y, z = p3
    depth = -x * math.sin(a) + z * math.cos(a)
    return (x * math.cos(a) + z * math.sin(a), y + _E[0] * depth), depth


def leaned(p3, lean):
    """An upper-body point tipped forward by `lean` degrees about the hips (head goes forward and down)."""
    if not lean:
        return p3
    L = math.radians(lean)
    x, y, z = p3
    dy = y - HIP_Y
    return x, HIP_Y + dy * math.cos(L) + z * math.sin(L), z * math.cos(L) - dy * math.sin(L)


# ------------------------------------------------------------------------------------------------ the skeleton
def _sub(a, b):
    return tuple(x - y for x, y in zip(a, b))


def _add(a, b):
    return tuple(x + y for x, y in zip(a, b))


def _mul(a, k):
    return tuple(x * k for x in a)


def _dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def _unit(a):
    n = math.sqrt(_dot(a, a)) or 1.0
    return _mul(a, 1 / n)


def ik3(root, target, l1, l2, pole):
    """Two bones from `root` towards `target` (lengths l1, l2): the middle joint bends towards `pole` (a direction).
    The end stops at full reach if the target is too far. Returns (middle, end)."""
    d = _sub(target, root)
    dist = math.sqrt(_dot(d, d)) or 1e-6
    dist = min(max(dist, abs(l1 - l2) + 1e-3), l1 + l2 - 1e-3)
    n = _unit(d)
    along = (l1 * l1 - l2 * l2 + dist * dist) / (2 * dist)
    h = math.sqrt(max(0.0, l1 * l1 - along * along))
    pv = _sub(pole, _mul(n, _dot(pole, n)))
    pv = _unit(pv) if _dot(pv, pv) > 1e-9 else _unit((n[1], -n[0], 0.0))
    mid = _add(_add(root, _mul(n, along)), _mul(pv, h))
    return mid, _add(root, _mul(n, dist))


POLES = {'out': (1.0, 0.4, -0.35), 'down': (0.35, 1.0, -0.25), 'back': (0.25, 0.3, -1.0), 'front': (0.2, 0.2, 1.0),
         'up': (0.5, -1.0, 0.0), 'in': (-0.6, 0.6, 0.4)}


def reach_ok(j, side, target, shape='fist'):
    """Can the hand reach `target` without stretching? (for the checks)"""
    d = _sub(target, j['sh' + side])
    return math.sqrt(_dot(d, d)) <= (F.UPPER + F.FORE) * 0.98 + F.HAND.get(shape, 14) + 1


def arm_to(j, side, target, pole='down', shape='fist'):
    """Put a hand's contact point (fist, palm, point...: figure.HAND) on `target` (torso frame, before any lean).
    `pole`: which way the elbow points ('out', 'down', 'back', 'front', 'up', 'in'), mirrored for the left arm."""
    sg = -1 if side == 'L' else 1
    px, py, pz = POLES[pole] if isinstance(pole, str) else pole
    up, fore = F.UPPER * 0.98, F.FORE * 0.98
    off = F.HAND.get(shape, 14)
    el, end = ik3(j['sh' + side], target, up, fore + off, (sg * px, py, pz))
    wr = _add(el, _mul(_unit(_sub(end, el)), fore))
    j['el' + side], j['wr' + side] = el, wr
    j.setdefault('hand', {})[side] = shape
    return j


def aim(j, side, target, pole='down'):
    """Point at `target` (torso frame): the arm nearly straight along the line from the shoulder, so the finger aims
    at it (Patriots 4 note 6: "the pointing must look like pointing"; a bent elbow aims the finger at the sky)."""
    sh = j['sh' + side]
    u = _unit(_sub(target, sh))
    return arm_to(j, side, _add(sh, _mul(u, (F.UPPER + F.FORE) * 0.97 + F.HAND['point'])), pole, 'point')


def standing(sp):
    """Standing relaxed: feet a little apart, arms hanging just in front of the body, hands loose fists."""
    sw = sp.get('shoulders', 150)
    j = {'bob': 0.0, 'lean': 0.0, 'hand': {}, 'behind': set(), 'props': []}
    stance = WOMAN_STANCE if sp.get('figure') in WOMAN_LEGS else 60
    for side, sg in (('L', -1), ('R', 1)):
        j['hip' + side] = (sg * 55, HIP_Y, 0.0)
        j['foot' + side] = (sg * stance, ANKLE_Y, 6.0)
        j['sh' + side] = (sg * (sw - 14), 60.0, 0.0)
        # A relaxed arm is never a straight rod (Sam, Ad-Vanced Notice note 16: "one long straight tube"), and the
        # elbow points a tiny bit OUT (Sam, note 17: a forearm angled out made the elbow point in, and too far): the
        # upper arm leans out a few degrees from the shoulder, the forearm comes back under it and a little forward,
        # a soft bend of about 10 degrees. Hands clear of the jacket (Sam), wrists near the crotch line.
        sh = j['sh' + side]
        up = _unit((sg * 0.12, 0.99, -0.04))     # Sam's four rest references (8 Nov, references/figure-rig/):
        fo = _unit((sg * -0.04, 0.99, 0.13))     # elbow at the waist, forearm back in, hands beside the upper thigh
        if sp.get('figure') in ('female', 'straight'):   # Open Wounds (chat 4; notes/learn/womans-build): the
            up = _unit((sg * 0.16, 0.99, -0.14))  # upper arm a little further out and the forearm straight under it,
            fo = _unit((sg * 0.02, 0.99, 0.21))   # so the waist and the hip's curve show between arm and body (the
            #                                       judge: arms hugging the sides hid them; tucked in, a column).
            # Chat 7: the upper arm a little further back (z -0.14; was -0.04, a man's): turned, the far arm hung in front
            # of her whole front edge, so the bust never showed (the judge: "straight side-on body"); her walking
            # photo, a little turned: the arm at her side, the top's curve ahead of it. The forearm comes forward
            # more (0.13 -> 0.21) so the far hand stays clear of the jacket's front (Sam: hands clear of the
            # jacket; at 0.02 it hid half behind the hem: castsheet match caught it). The front view is the same
            # (z is depth).
        el = _add(sh, _mul(up, F.UPPER * 0.98))
        j['el' + side], j['wr' + side] = el, _add(el, _mul(fo, F.FORE * 0.98))
        j['hand'][side] = 'fist'
    return j


def set_arm(j, side, swing, bend, out=0.12):
    """Arm joints from angles (both bones keep the rig's lengths): swing brings the upper arm forward (+) or back."""
    sg = -1 if side == 'L' else 1
    sx, sy, sz = j['sh' + side]
    u = (sg * math.sin(out), math.cos(swing) * math.cos(out), math.sin(swing) * math.cos(out))
    el = (sx + u[0] * F.UPPER * 0.98, sy + u[1] * F.UPPER * 0.98, sz + u[2] * F.UPPER * 0.98)
    a = swing + bend
    v = (sg * math.sin(out) * 0.5, math.cos(a), math.sin(a))
    n = math.sqrt(sum(c * c for c in v))
    wr = tuple(e + c / n * F.FORE * 0.98 for e, c in zip(el, v))
    j['el' + side], j['wr' + side] = el, wr


# ------------------------------------------------------------------------------------------------ the limbs
def tube(p, pts, widths, col):
    """One smooth limb through the points (rounded at each joint), tapering through `widths`."""
    P = np.asarray(pts, float)
    dense, wd = [], []
    for i in range(len(P) - 1):
        for u in np.linspace(0, 1, 12, endpoint=False):
            dense.append(P[i] + (P[i + 1] - P[i]) * u)
            wd.append(widths[i] + (widths[i + 1] - widths[i]) * u)
    dense.append(P[-1])
    wd.append(widths[-1])
    D = np.asarray(dense)
    T = np.gradient(D, axis=0)
    N = np.stack([-T[:, 1], T[:, 0]], 1) / (np.hypot(*T.T)[:, None] + 1e-9)
    left = D + N * np.asarray(wd)[:, None]
    right = D - N * np.asarray(wd)[:, None]
    p.poly(curve([tuple(v) for v in np.vstack([left, right[::-1]])], 2), col, INK, 2.6)


def _hull(pts):
    pts = sorted(set((round(x, 2), round(y, 2)) for x, y in pts))
    if len(pts) < 3:
        return pts

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
    lo, hi = [], []
    for q in pts:
        while len(lo) >= 2 and cross(lo[-2], lo[-1], q) <= 0:
            lo.pop()
        lo.append(q)
    for q in reversed(pts):
        while len(hi) >= 2 and cross(hi[-2], hi[-1], q) <= 0:
            hi.pop()
        hi.append(q)
    return lo[:-1] + hi[:-1]


def knee_of(j, side):
    hip, foot = j['hip' + side], j['foot' + side]
    sg = -1 if side == 'L' else 1
    knee, _ = ik3(hip, foot, THIGH, SHIN, j.get('knee_pole' + side, (0.12 * sg, 0.0, 1.0)))
    # Standing, the leg is a few units short of full reach, and the solver bent every standing knee ~36 units forward:
    # in side views everyone stood with bent knees (Sam, Ad-Vanced Notice note 15). Near full reach the knee now locks
    # onto the hip-ankle line, eased in (no pop as a walking leg straightens); a real bend (seated, kneeling,
    # mid-stride) is untouched.
    d = _sub(foot, hip)
    dist = math.sqrt(_dot(d, d))
    u = min(1.0, max(0.0, (dist / (THIGH + SHIN) - 0.95) / 0.035))
    lock = u * u * (3 - 2 * u)
    if lock > 0:
        line = _add(hip, _mul(d, THIGH / (THIGH + SHIN)))
        knee = _add(_mul(knee, 1 - lock), _mul(line, lock))
    return knee


