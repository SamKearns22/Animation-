def back_neck(y, nw=1.0):
    """Half width of the neck seen from behind at body height y (y -80 the top, 10 the collar), at neck_w nw."""
    u = min(1.0, max(0.0, (y + 80.0) / 90.0))
    return nw * (BACK_NECK[0] + (BACK_NECK[1] - BACK_NECK[0]) * (0.25 * u + 0.75 * u ** 3))
