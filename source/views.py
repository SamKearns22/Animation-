    for y in ys:
        xs = [x0 + (x1 - x0) * (y - y0) / (y1 - y0) for (x0, y0), (x1, y1) in zip(poly, poly[1:] + poly[:1])
              if (y0 - y) * (y1 - y) <= 0 and y0 != y1]
        fr.append(max(xs) if xs else 1.0)
        bk.append(-min(xs) if xs else 1.0)
