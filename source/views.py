def tube(p, pts, widths, col):
    """One smooth limb through the points (rounded at each joint), tapering through `widths`."""
    P = np.asarray(pts, float)
    dense, wd = [], []
    for i in range(len(P) - 1):
        for u in np.linspace(0, 1, 12, endpoint=False):
            dense.append(P[i] + (P[i + 1] - P[i]) * u)
            wd.append(widths[i] + (widths[i + 1] - widths[i]) * u)
    dense.append(P[-1])
    wd.append(widths[-1])
    D = np.asarray(dense)
    T = np.gradient(D, axis=0)
    N = np.stack([-T[:, 1], T[:, 0]], 1) / (np.hypot(*T.T)[:, None] + 1e-9)
    left = D + N * np.asarray(wd)[:, None]
    right = D - N * np.asarray(wd)[:, None]
    p.poly(curve([tuple(v) for v in np.vstack([left, right[::-1]])], 2), col, INK, 2.6)


def _hull(pts):
    pts = sorted(set((round(x, 2), round(y, 2)) for x, y in pts))
    if len(pts) < 3:
        return pts

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
    lo, hi = [], []
    for q in pts:
        while len(lo) >= 2 and cross(lo[-2], lo[-1], q) <= 0:
            lo.pop()
        lo.append(q)
    for q in reversed(pts):
        while len(hi) >= 2 and cross(hi[-2], hi[-1], q) <= 0:
            hi.pop()
        hi.append(q)
    return lo[:-1] + hi[:-1]


def knee_of(j, side):
    hip, foot = j['hip' + side], j['foot' + side]
    sg = -1 if side == 'L' else 1
    knee, _ = ik3(hip, foot, THIGH, SHIN, j.get('knee_pole' + side, (0.12 * sg, 0.0, 1.0)))
    # Standing, the leg is a few units short of full reach, and the solver bent every standing knee ~36 units forward:
    # in side views everyone stood with bent knees (Sam, Ad-Vanced Notice note 15). Near full reach the knee now locks
    # onto the hip-ankle line, eased in (no pop as a walking leg straightens); a real bend (seated, kneeling,
    # mid-stride) is untouched.
    d = _sub(foot, hip)
    dist = math.sqrt(_dot(d, d))
    u = min(1.0, max(0.0, (dist / (THIGH + SHIN) - 0.95) / 0.035))
    lock = u * u * (3 - 2 * u)
    if lock > 0:
        line = _add(hip, _mul(d, THIGH / (THIGH + SHIN)))
        knee = _add(_mul(knee, 1 - lock), _mul(line, lock))
    return knee


