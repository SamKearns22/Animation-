def finish(img):
    return img.convert('RGB').resize((W, H), Image.LANCZOS)


def main():
    mode = sys.argv[1]
    if mode == 'stills':
        out = sys.argv[2]
        os.makedirs(out, exist_ok=True)
        only = sys.argv[3:] or [b[0] for b in BOARD]
        for n, name, _, fn in BOARD:
            if n in only:
                finish(fn()).save(os.path.join(out, f'shot{n}.png'))
                print('shot', n, flush=True)
    elif mode == 'sheet':
        out, dst = sys.argv[2], sys.argv[3]
        cw, ch, lab = 540, 960, 120
        rows = (len(BOARD) + 2) // 3
        sheet = Image.new('RGB', (cw * 3 + 80, (ch + lab + 10) * rows + 30), (245, 242, 236))
        d = ImageDraw.Draw(sheet)
        f1 = ImageFont.truetype(SANS, 34)
        f2 = ImageFont.truetype(SANS, 26)
        for i, (n, name, when, _) in enumerate(BOARD):
            im = Image.open(os.path.join(out, f'shot{n}.png')).resize((cw, ch), Image.LANCZOS)
            x, y = 20 + (i % 3) * (cw + 20), 20 + (i // 3) * (ch + lab + 10)
            sheet.paste(im, (x, y))
            d.text((x + 4, y + ch + 12), f'{n}. {name}', font=f1, fill=(20, 20, 20))
            d.text((x + 4, y + ch + 58), when, font=f2, fill=(90, 90, 90))
        sheet.save(dst, quality=88)


def _house_limbs():
    """The house style is always on (Sam, 21 Oct: 'no future boxy arms in our videos'): the smooth arms and legs
    (limbs.py) and the arm checker (figure.guard) switch on for every film that draws people, whatever file it was
    started from (Strictly Crabs' judges began from Poker Mon's file and came out boxy). Both are safe to call again,
    so films that switch them on themselves are unchanged."""
    import figure
    import limbs
    me = sys.modules[__name__]
    figure.guard(me)
    limbs.install(me)


_house_limbs()
