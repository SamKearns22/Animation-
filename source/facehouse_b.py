    lid = sp.get('lid4', 0.12)
    for sgn in (-1, 1):
        ex, ey = f(sgn * L['ecx'], L['eye_y'])
        for u in np.linspace(0.05, 1.0, 3 + int(4 * k)):
            x, y = ex + sgn * w * u, ey - h * (1 - u * u) * (1 - lid)
            ln = (3 + 6 * k) * (0.6 + 0.6 * u)
            a = math.radians(100 - 55 * u)                # straight up at the middle, out at the corner
