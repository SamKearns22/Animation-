def _v(*a):
    return np.array(a, float)


def _unit(a):
    a = np.asarray(a, float)
    return a / (np.linalg.norm(a) or 1.0)


def ease(u):
    u = max(0.0, min(1.0, u))
    return u * u * (3 - 2 * u)


