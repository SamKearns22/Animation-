#!/usr/bin/env python3
"""maps: every code file opens with a MAP (cost-spike fix step 5, Sam's Y, 27 Nov; rule 61: "a film's code opens with
a MAP; read only the lines a note touches"). On 27 Nov 176 of 318 files had none, so a chat opening one read it whole
or searched it.

MAP
  missing() .... the code files (source/*.py, .claude/hooks/*.py) of BIG lines or more whose opening docstring holds
                 no MAP.
  make() ....... the MAP for one file, from its own structure (ast): one line per top-level def, class and table, with
                 its line and the first line of its docstring. Written into the opening docstring (a new one if the
                 file has none), marked "generated", so it can be made again after the file changes.
  add() ........ make() written into each file that lacks one; nothing else in the file changes (code, names and
                 order are untouched; only the docstring and so the line numbers below it move).
  faults() ..... handover.py end: a file of BIG lines or more with no MAP is a STOP-free fault, named with the command
                 that writes one. A generated MAP that no longer matches its file (a def added, renamed or removed) is
                 named too, so the MAP never lies.
  test() ....... kittest maps_on_big_files

    python3 source/maps.py                list the files lacking one
    python3 source/maps.py add [FILE...]  write the MAP into them (all lacking, when no FILE)
    python3 source/maps.py test
"""
import ast
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DIRS = ('source', os.path.join('.claude', 'hooks'))
BIG = 150
TAG = 'MAP (generated by source/maps.py; make again with: python3 source/maps.py add FILE)'


def _files(root=ROOT):
    out = []
    for d in DIRS:
        p = os.path.join(root, d)
        if os.path.isdir(p):
            out += [os.path.join(d, f) for f in sorted(os.listdir(p)) if f.endswith('.py')]
    return out


def _doc_node(tree):
    if tree.body and isinstance(tree.body[0], ast.Expr) and isinstance(getattr(tree.body[0], 'value', None),
                                                                        ast.Constant) \
            and isinstance(tree.body[0].value.value, str):
        return tree.body[0]
    return None


def has_map(src):
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return True                                  # touch.py flags an unparsable file; not this check's fault
    return 'MAP' in (ast.get_docstring(tree) or '')


def missing(root=ROOT, big=BIG):
    out = []
    for rel in _files(root):
        src = open(os.path.join(root, rel), encoding='utf-8', errors='replace').read()
        if len(src.splitlines()) >= big and not has_map(src):
            out.append(rel)
    return out


def _clean(text):
    return re.sub(r'\s+', ' ', text.replace('\\', '/').replace('"""', "'").replace("'''", "'")).strip()


def entries(tree):
    rows = []
    for n in tree.body:
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            doc = _clean((ast.get_docstring(n) or '').split('\n\n')[0])[:84]
            rows.append((n.lineno, ('class ' if isinstance(n, ast.ClassDef) else '') + n.name
                         + ('' if isinstance(n, ast.ClassDef) else '()'), doc))
        elif isinstance(n, ast.Assign) and len(n.targets) == 1 and isinstance(n.targets[0], ast.Name) \
                and n.targets[0].id.isupper() and n.targets[0].id.strip('_'):
            rows.append((n.lineno, n.targets[0].id, '(table)'))
    return rows


def make(src):
    """The MAP lines for one file's code: one line per def and class (names only, no line numbers: those move with
    every edit), then its tables (upper-case names) run together on a few lines."""
    tree = ast.parse(src)
    rows = entries(tree)
    fns = [r for r in rows if r[2] != '(table)']
    tables = [r[1] for r in rows if r[2] == '(table)']
    w = min(28, max([len(r[1]) for r in fns] + [8]) + 1)
    lines = [TAG]
    for _, name, doc in fns:
        lines.append(f'  {name} {"." * max(2, w - len(name))} {doc}'.rstrip())
    row = '  tables:'
    for t in tables:
        if len(row) + len(t) > 112:
            lines.append(row.rstrip(','))
            row = '  tables:'
        row += f' {t},'
    if tables:
        lines.append(row.rstrip(','))
    return lines


def add(rel, root=ROOT):
    """Writes the MAP into one file's opening docstring, after its first paragraph (so it sits in the first lines,
    where preflight.py and a reader look). Returns 'added', 'remade' or why it could not."""
    p = os.path.join(root, rel)
    src = open(p, encoding='utf-8').read()
    tree = ast.parse(src)
    block = make(src)
    lines = src.split('\n')
    node = _doc_node(tree)
    had = TAG in src
    if not had and has_map(src):
        return 'skipped: it already has a MAP written by hand'
    if node is None:
        at = 0
        while at < len(lines) and (lines[at].startswith('#!') or re.match(r'#.*coding[:=]', lines[at])):
            at += 1
        out = lines[:at] + ['"""' + os.path.basename(rel)[:-3] + ': ' + block[0]] + block[1:] + ['"""'] + lines[at:]
    elif not re.match(r'\s*[rRuU]?("""|\'\'\')', lines[node.lineno - 1]):
        return 'skipped: its opening docstring is not triple-quoted'
    else:
        l0, el, ec = node.lineno - 1, node.end_lineno - 1, node.end_col_offset - 3
        out = list(lines)
        tag_at = next((i for i in range(l0, el + 1) if TAG in out[i]), None)
        if tag_at is not None:                           # remake: the old generated lines out, the new ones in
            j = tag_at + 1
            while j < el and out[j].startswith('  '):
                j += 1
            head = out[tag_at][:out[tag_at].index(TAG)]
            out[tag_at:j] = [head + block[0]] + block[1:]
        elif l0 == el:                                   # one line: """text"""
            first = out[l0]
            out[l0:l0 + 1] = [first[:ec], ''] + block + [first[ec:]]
        else:
            blank = next((i for i in range(l0 + 1, el) if not out[i].strip()), None)
            if blank is not None:
                out[blank + 1:blank + 1] = block + ['']
            else:
                last = out[el]
                tail = [last[:ec]] if last[:ec].strip() else []
                out[el:el + 1] = tail + [''] + block + [last[ec:]]
    out = '\n'.join(out)
    try:
        t2 = ast.parse(out)
    except SyntaxError as e:
        return f'skipped: the MAP would not parse ({e})'
    if ast.dump(_strip_doc(t2)) != ast.dump(_strip_doc(tree)):
        return 'skipped: the code itself would change'
    with open(p, 'w', encoding='utf-8') as f:
        f.write(out)
    return 'remade' if had else 'added'


def _strip_doc(tree):
    """The code without its opening docstring (to prove adding a MAP changes nothing else)."""
    body = tree.body[1:] if _doc_node(tree) else tree.body
    return ast.Module(body=body, type_ignores=[])


def out_of_date(root=ROOT):
    """Files whose generated MAP no longer lists the same names as the code."""
    out = []
    for rel in _files(root):
        src = open(os.path.join(root, rel), encoding='utf-8', errors='replace').read()
        if TAG not in src:
            continue
        try:
            tree = ast.parse(src)
        except SyntaxError:
            continue
        node = _doc_node(tree)
        doc = node.value.value if node else ''        # raw: get_docstring() would strip the MAP's indent
        if TAG not in doc:
            continue
        want = [r[1].replace('class ', '') for r in entries(tree) if r[2] != '(table)']
        have = [ln.strip().split(' ')[1] if ln.strip().startswith('class ') else ln.strip().split(' ')[0]
                for ln in doc[doc.index(TAG):].split('\n\n')[0].split('\n')[1:] if ln.startswith('  ') and ln.strip()
                and not ln.startswith('  tables:')]
        if have != want:
            out.append(rel)
    return out


def faults(root=ROOT):
    out = [f'{rel} has no MAP at the top ({BIG}+ lines): python3 source/maps.py add {rel}' for rel in missing(root)]
    out += [f'{rel}: its generated MAP no longer matches its defs: python3 source/maps.py add {rel}'
            for rel in out_of_date(root)]
    return out


def test():
    """The fault, saved as an example: chat 30 opened a 3,000-line film file with no MAP and read it in ranges
    (rule 61 had no check). Here: a big file with no MAP is named, add() writes one without changing the code, a
    one-line docstring and a file with none both work, a renamed def makes the MAP out of date, and add() remakes it."""
    import shutil
    import tempfile
    d = tempfile.mkdtemp()
    os.makedirs(os.path.join(d, 'source'))
    bad = []
    try:
        body = ''.join(f'def f{i}(x):\n    """Does thing {i}: a \\\\ backslash and \'quotes\'."""\n    return x + {i}\n\n'
                       for i in range(60))
        files = {'a.py': '#!/usr/bin/env python3\n"""A film file, no map."""\nimport os\nTABLE = 1\n\n' + body,
                 'b.py': 'import os\n\n' + body,
                 'c.py': '"""Long docstring.\n\nMore words.\n"""\n' + body,
                 'small.py': '"""Small."""\nx = 1\n'}
        for k, v in files.items():
            open(os.path.join(d, 'source', k), 'w').write(v)
        m = missing(d)
        if m != ['source/a.py', 'source/b.py', 'source/c.py']:
            bad.append(f'missing {m}')
        for rel in m:
            r = add(rel, d)
            if r != 'added':
                bad.append(f'{rel}: {r}')
        if missing(d) or faults(d):
            bad.append(f'after add: {missing(d)} {faults(d)}')
        src = open(os.path.join(d, 'source', 'a.py')).read()
        if not src.startswith('#!/usr/bin/env python3\n"""A film file') or 'f59() ' not in src or 'tables: TABLE' not in src:
            bad.append('a.py map: ' + src[:300])
        p = os.path.join(d, 'source', 'c.py')
        text = open(p).read().replace('def f7(', 'def renamed7(')
        open(p, 'w').write(text)
        if faults(d) != ['source/c.py: its generated MAP no longer matches its defs: python3 source/maps.py add source/c.py']:
            bad.append(f'rename not caught: {faults(d)}')
        if add('source/c.py', d) != 'remade' or faults(d) or open(p).read().count(TAG) != 1:
            bad.append('remake failed')
    finally:
        shutil.rmtree(d, ignore_errors=True)
    print('maps test: ' + ('OK' if not bad else 'FAILED: ' + '; '.join(bad)))
    return not bad, '; '.join(bad) or 'a big file with no MAP named; MAP added with the code unchanged; a rename caught and remade'


def main(argv):
    if argv[:1] == ['test']:
        return 0 if test()[0] else 1
    if argv[:1] == ['add']:
        todo = argv[1:] or missing()
        res = {}
        for rel in todo:
            r = add(os.path.relpath(os.path.abspath(rel), ROOT) if os.path.exists(rel) else rel)
            res.setdefault(r.split(':')[0], []).append(rel if r in ('added', 'remade') else f'{rel} ({r})')
        for k, v in res.items():
            print(f'maps: {k} {len(v)}: ' + ', '.join(v[:12]) + (' ...' if len(v) > 12 else ''))
        return 0
    m = missing()
    print(f'maps: {len(m)} file(s) of {BIG}+ lines lack a MAP' + (': ' + ', '.join(m) if m else ''))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
