"""The quiet cost line (Sam, 19 Nov; job 2).

MAP (generated by source/maps.py; make again with: python3 source/maps.py add FILE)
  line() .... 'film so far X% of a week'.
  record() .. Record the line (ledger + notes), quietly. Returns None (nothing is ever shown).
  shown() ... Films Sam asked to see the cost line for after every chat (one name a line in notes/
  for_sam() .. The plain line for Sam: the film's cost so far against the plan, the last chat's cos
  faults() .. For handover.py end: the line is recorded here; for a film Sam asked to see (Sam's Y
  tables: DIR, ROOT, MARK, SHOW_FILE

At every handover the film's cost so far is RECORDED (in the film's ledger and its notes), quietly, and never shown
to Sam: the forecast and the cost warnings were deleted on Sam's word (R8 check audit, 26 Nov, his answer 2: the
paused budget alarms go; the quiet tracking stays).

  python3 source/costline.py FILM [--notes PATH]     record the line (prints nothing)
  python3 source/costline.py show FILM               the plain line for Sam (films listed in notes/cost-line-to-sam.txt
                                                     get it at every handover: Sam's Y, 28 Nov)
"""
import datetime
import os
import re
import sys

DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(DIR)
sys.path.insert(0, DIR)
MARK = 'Cost line (recorded every handover; shown to Sam only on a problem):'

def line(d):
    """'film so far X% of a week'."""
    import ledger
    spent = ledger.totals(d)[0]
    return f'film so far {spent:g}% of a week', spent


def record(film, notes=None):
    """Record the line (ledger + notes), quietly. Returns None (nothing is ever shown)."""
    import ledger
    d = ledger.load(film)
    if not d.get('chats'):
        return None
    text, spent = line(d)
    d.setdefault('cost_log', []).append({'date': str(datetime.date.today()), 'spent': spent})
    ledger.store(d)
    p = notes or os.path.join(ROOT, 'notes', f'{film}.md')
    if os.path.exists(p):
        body = open(p, encoding='utf-8').read()
        entry = f'{MARK} {text} ({datetime.date.today()})'
        body = re.sub(r'(?m)^' + re.escape(MARK) + r'.*\n?', '', body).rstrip('\n') + '\n\n' + entry + '\n'
        open(p, 'w', encoding='utf-8').write(body)
    return None


SHOW_FILE = os.path.join(ROOT, 'notes', 'cost-line-to-sam.txt')   # Sam's Y, 28 Nov: films whose every chat ends with it


def shown(film):
    """Films Sam asked to see the cost line for after every chat (one name a line in notes/cost-line-to-sam.txt)."""
    try:
        names = {x.strip() for x in open(SHOW_FILE, encoding='utf-8') if x.strip() and not x.startswith('#')}
    except OSError:
        return False
    return film in names or film.replace('-', '_') in names or film.replace('_', '-') in names


def for_sam(film):
    """The plain line for Sam: the film's cost so far against the plan, the last chat's cost, where most of it went."""
    import ledger
    d = ledger.load(film)
    if not d.get('chats'):
        return None
    spent = ledger.totals(d)[0]
    last = d['chats'][-1]
    top = sorted((last.get('kinds') or {}).items(), key=lambda kv: -kv[1])[:2]
    went = ', '.join(f'{k} {v:g}%' for k, v in top)
    plan = f' of the {d["estimate"]:g}% planned' if d.get('estimate') else ''
    return (f'Cost: {spent:g}% of a week so far{plan}; the last chat {last["cost"]:g}%'
            + (f' (most of it: {went})' if went else '') + '.')


def faults(film, notes=None):
    """For handover.py end: the line is recorded here; for a film Sam asked to see (Sam's Y, 28 Nov), the line to put
    in the chat's last message is printed."""
    record(film, notes)
    if shown(film):
        t = for_sam(film)
        if t:
            return [f'COST LINE FOR SAM (his Y, 28 Nov: after every chat of this film): put this in your last message: {t}']
    return []


if __name__ == '__main__':
    a = sys.argv[1:]
    if not a:
        sys.exit(__doc__)
    if a[0] == 'show':
        print(for_sam(a[1]) or 'no chats in the ledger yet')
        sys.exit(0)
    record(a[0], a[a.index('--notes') + 1] if '--notes' in a else None)
    print('cost line recorded (quietly)')
